package ru.Lab7;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.h2.tools.RunScript;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.sql.*;
import java.util.Scanner;

public class Main {
    private static final String URL = "jdbc:h2:./data/musicdb";
    private static final String USER = "sa";
    private static final String PASSWORD = "";

    public static void main(String[] args) {
        try (Connection connection = DriverManager.getConnection(URL, USER, PASSWORD)) {
            connection.setAutoCommit(false);
            try {
                createMusicSchema(connection);
                createPeopleTables(connection);
                loadMusicScript(connection);
                showAllMusic(connection);                 // Задание 1
                showMusicWithoutMAndT(connection);         // Задание 2
                addFavoriteSong(connection);               // Задание 3
                importJson(connection);                    // Задание 4
                showBooksSorted(connection);               // Задание 5
                showBooksBefore2000(connection);            // Задание 6
                addCurrentVisitor(connection);              // Задание 7
                connection.commit();
                dropPeopleTables(connection);               // Задание 8
                connection.commit();
            } catch (Exception e) {
                connection.rollback();
                throw e;
            }
        } catch (Exception e) {
            System.err.println("Ошибка выполнения лабораторной: " + e.getMessage());
            e.printStackTrace();
        }
    }

    private static void createMusicSchema(Connection c) throws SQLException {
        try (Statement st = c.createStatement()) {
            st.execute("CREATE SCHEMA IF NOT EXISTS study");
        }
    }

    private static void loadMusicScript(Connection c) throws Exception {
        try (InputStream in = Main.class.getResourceAsStream("/music-create.sql")) {
            if (in == null) throw new IllegalStateException("Не найден music-create.sql");
            RunScript.execute(c, new InputStreamReader(in, StandardCharsets.UTF_8));
        }
    }

    private static void createPeopleTables(Connection c) throws SQLException {
        try (Statement st = c.createStatement()) {
            st.execute("""
                CREATE TABLE IF NOT EXISTS visitors (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(100) NOT NULL,
                    surname VARCHAR(100) NOT NULL,
                    phone VARCHAR(30) NOT NULL UNIQUE,
                    subscribed BOOLEAN NOT NULL
                )
                """);
            st.execute("""
                CREATE TABLE IF NOT EXISTS books (
                    isbn VARCHAR(20) PRIMARY KEY,
                    name VARCHAR(300) NOT NULL,
                    author VARCHAR(200) NOT NULL,
                    publishing_year INT NOT NULL,
                    publisher VARCHAR(200) NOT NULL
                )
                """);
            st.execute("""
                CREATE TABLE IF NOT EXISTS visitor_books (
                    visitor_id BIGINT NOT NULL REFERENCES visitors(id),
                    isbn VARCHAR(20) NOT NULL REFERENCES books(isbn),
                    PRIMARY KEY (visitor_id, isbn)
                )
                """);
        }
    }

    private static void showAllMusic(Connection c) throws SQLException {
        System.out.println("\\n=== Задание 1. Все музыкальные композиции ===");
        try (Statement st = c.createStatement();
             ResultSet rs = st.executeQuery("SELECT id, name FROM study.music ORDER BY id")) {
            while (rs.next()) System.out.printf("%d. %s%n", rs.getInt("id"), rs.getString("name"));
        }
    }

    private static void showMusicWithoutMAndT(Connection c) throws SQLException {
        System.out.println("\\n=== Задание 2. Названия без букв m и t ===");
        String sql = """
            SELECT id, name FROM study.music
            WHERE LOWER(name) NOT LIKE '%m%'
              AND LOWER(name) NOT LIKE '%t%'
            ORDER BY id
            """;
        try (Statement st = c.createStatement(); ResultSet rs = st.executeQuery(sql)) {
            while (rs.next()) System.out.println(rs.getInt("id") + ". " + rs.getString("name"));
        }
    }

    private static void addFavoriteSong(Connection c) throws SQLException {
        System.out.println("\\n=== Задание 3. Добавление композиции ===");
        String sql = "INSERT INTO study.music(id, name) " +
                "SELECT COALESCE(MAX(id), 0) + 1, ? FROM study.music";
        try (PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, "Nothing Else Matters");
            ps.executeUpdate();
        }
        System.out.println("Добавлена композиция: Nothing Else Matters");
    }

    private static void importJson(Connection c) throws Exception {
        System.out.println("\\n=== Задание 4. Импорт visitors и books из JSON ===");
        ObjectMapper mapper = new ObjectMapper();
        try (InputStream in = Main.class.getResourceAsStream("/books.json")) {
            if (in == null) throw new IllegalStateException("Не найден books.json");
            JsonNode visitors = mapper.readTree(in);
            for (JsonNode visitor : visitors) {
                long visitorId = findOrInsertVisitor(c, visitor);
                JsonNode favoriteBooks = visitor.path("favoriteBooks");
                for (JsonNode book : favoriteBooks) {
                    String isbn = book.path("isbn").asText();
                    insertBookIfAbsent(c, book);
                    try (PreparedStatement ps = c.prepareStatement(
                            "INSERT INTO visitor_books(visitor_id, isbn) " +
                                    "SELECT ?, ? WHERE NOT EXISTS " +
                                    "(SELECT 1 FROM visitor_books WHERE visitor_id=? AND isbn=?)")) {
                        ps.setLong(1, visitorId);
                        ps.setString(2, isbn);
                        ps.setLong(3, visitorId);
                        ps.setString(4, isbn);
                        ps.executeUpdate();
                    }
                }
            }
        }
        System.out.println("Импорт завершён. Повторные посетители и книги не дублируются.");
    }

    private static long findOrInsertVisitor(Connection c, JsonNode v) throws SQLException {
        String phone = v.path("phone").asText();
        try (PreparedStatement ps = c.prepareStatement("SELECT id FROM visitors WHERE phone=?")) {
            ps.setString(1, phone);
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) return rs.getLong(1);
            }
        }
        String sql = "INSERT INTO visitors(name, surname, phone, subscribed) VALUES (?, ?, ?, ?)";
        try (PreparedStatement ps = c.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            ps.setString(1, v.path("name").asText());
            ps.setString(2, v.path("surname").asText());
            ps.setString(3, phone);
            ps.setBoolean(4, v.path("subscribed").asBoolean());
            ps.executeUpdate();
            try (ResultSet keys = ps.getGeneratedKeys()) {
                if (keys.next()) return keys.getLong(1);
            }
        }
        throw new SQLException("Не удалось получить id посетителя");
    }

    private static void insertBookIfAbsent(Connection c, JsonNode b) throws SQLException {
        String sql = """
            INSERT INTO books(isbn, name, author, publishing_year, publisher)
            SELECT ?, ?, ?, ?, ?
            WHERE NOT EXISTS (SELECT 1 FROM books WHERE isbn=?)
            """;
        try (PreparedStatement ps = c.prepareStatement(sql)) {
            String isbn = b.path("isbn").asText();
            ps.setString(1, isbn);
            ps.setString(2, b.path("name").asText());
            ps.setString(3, b.path("author").asText());
            ps.setInt(4, b.path("publishingYear").asInt());
            ps.setString(5, b.path("publisher").asText());
            ps.setString(6, isbn);
            ps.executeUpdate();
        }
    }

    private static void showBooksSorted(Connection c) throws SQLException {
        System.out.println("\\n=== Задание 5. Книги по году издания ===");
        try (Statement st = c.createStatement();
             ResultSet rs = st.executeQuery("SELECT name, author, publishing_year FROM books ORDER BY publishing_year, name")) {
            while (rs.next()) printBook(rs);
        }
    }

    private static void showBooksBefore2000(Connection c) throws SQLException {
        System.out.println("\\n=== Задание 6. Книги до 2000 года ===");
        try (PreparedStatement ps = c.prepareStatement(
                "SELECT name, author, publishing_year FROM books WHERE publishing_year < ? ORDER BY publishing_year")) {
            ps.setInt(1, 2000);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) printBook(rs);
            }
        }
    }

    private static void printBook(ResultSet rs) throws SQLException {
        System.out.printf("%d | %s — %s%n", rs.getInt("publishing_year"),
                rs.getString("name"), rs.getString("author"));
    }

    private static void addCurrentVisitor(Connection c) throws SQLException {
        System.out.println("\\n=== Задание 7. Добавление ваших данных ===");
        try (Scanner scanner = new Scanner(System.in)) {
            System.out.print("Ваше имя: ");
            String name = scanner.nextLine().trim();
            System.out.print("Фамилия: ");
            String surname = scanner.nextLine().trim();
            System.out.print("Телефон (уникальный): ");
            String phone = scanner.nextLine().trim();
            System.out.print("Подписаны? (true/false): ");
            boolean subscribed = Boolean.parseBoolean(scanner.nextLine().trim());

            long visitorId;
            try (PreparedStatement ps = c.prepareStatement(
                    "INSERT INTO visitors(name, surname, phone, subscribed) VALUES (?, ?, ?, ?)",
                    Statement.RETURN_GENERATED_KEYS)) {
                ps.setString(1, name);
                ps.setString(2, surname);
                ps.setString(3, phone);
                ps.setBoolean(4, subscribed);
                ps.executeUpdate();
                try (ResultSet keys = ps.getGeneratedKeys()) {
                    if (!keys.next()) throw new SQLException("Не получен id посетителя");
                    visitorId = keys.getLong(1);
                }
            }

            System.out.print("Сколько любимых книг добавить? ");
            int count = Integer.parseInt(scanner.nextLine().trim());
            for (int i = 0; i < count; i++) {
                System.out.printf("Книга %d — название: ", i + 1);
                String title = scanner.nextLine().trim();
                System.out.print("Автор: ");
                String author = scanner.nextLine().trim();
                System.out.print("Год издания: ");
                int year = Integer.parseInt(scanner.nextLine().trim());
                System.out.print("ISBN (уникальный): ");
                String isbn = scanner.nextLine().trim();
                System.out.print("Издательство: ");
                String publisher = scanner.nextLine().trim();
                try (PreparedStatement ps = c.prepareStatement("""
                        INSERT INTO books(isbn, name, author, publishing_year, publisher)
                        SELECT ?, ?, ?, ?, ?
                        WHERE NOT EXISTS (SELECT 1 FROM books WHERE isbn=?)
                        """)) {
                    ps.setString(1, isbn); ps.setString(2, title); ps.setString(3, author);
                    ps.setInt(4, year); ps.setString(5, publisher); ps.setString(6, isbn);
                    ps.executeUpdate();
                }
                try (PreparedStatement ps = c.prepareStatement(
                        "INSERT INTO visitor_books(visitor_id, isbn) VALUES (?, ?)")) {
                    ps.setLong(1, visitorId); ps.setString(2, isbn); ps.executeUpdate();
                }
            }

            System.out.println("\\nДобавленные данные, прочитанные из БД:");
            try (PreparedStatement ps = c.prepareStatement("""
                    SELECT v.name, v.surname, v.phone, b.name AS book_name,
                           b.author, b.publishing_year, b.isbn
                    FROM visitors v
                    LEFT JOIN visitor_books vb ON vb.visitor_id=v.id
                    LEFT JOIN books b ON b.isbn=vb.isbn
                    WHERE v.id=?
                    ORDER BY b.publishing_year
                    """)) {
                ps.setLong(1, visitorId);
                try (ResultSet rs = ps.executeQuery()) {
                    while (rs.next()) {
                        System.out.printf("%s %s (%s) | %s | %s | %s | ISBN %s%n",
                                rs.getString("name"), rs.getString("surname"), rs.getString("phone"),
                                rs.getString("book_name"), rs.getString("author"),
                                rs.getObject("publishing_year"), rs.getString("isbn"));
                    }
                }
            }
        }
    }

    private static void dropPeopleTables(Connection c) throws SQLException {
        System.out.println("\\n=== Задание 8. Удаление таблиц ===");
        try (Statement st = c.createStatement()) {
            st.execute("DROP TABLE IF EXISTS visitor_books");
            st.execute("DROP TABLE IF EXISTS books");
            st.execute("DROP TABLE IF EXISTS visitors");
        }
        System.out.println("Таблицы visitor_books, books и visitors удалены.");
    }
}